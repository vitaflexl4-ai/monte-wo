#!/usr/bin/env python3
"""Build the native web bundle consumed by the Capacitor Android/iOS shells.

Source of truth stays `public/` (generated by `npm run build`). This script never edits
`public/`; it writes a derived, deterministic copy to `build/native/` (the Capacitor
`webDir`), with the adjustments a packaged app needs:

1. The MONTE WO app shell (`public/dashboard/index.html`) becomes the root `index.html`,
   so the native app opens directly in the app, not on the marketing homepage.
2. Directory-style internal links (`/methodology/`) are rewritten to explicit files
   (`/methodology/index.html`). Capacitor's local asset servers (Android
   `WebViewLocalServer` html5mode, iOS `Router`) return the ROOT index for every
   extension-less path, so without this rewrite every deep link would reopen the shell.
3. Every HTML document gets `<script>window.__MW_NATIVE=true</script>` first in `<head>`;
   `public/*.js` checks it to skip service-worker registration (no `sw.js` in the bundle).
4. Cloudflare-only and web-only files are excluded: `_headers`, `_redirects` (Pages
   config), `sw.js` (no service worker inside the packaged app; assets are local),
   `robots.txt` / `sitemap.xml` (crawler files) and `strength/admin/` (reviewer/admin
   console, which must only be reached through the Cloudflare Access-protected origin).

Run: `python3 scripts/build_native.py` (or `npm run build:native`) after `npm run build`,
then `npx cap sync` to copy the bundle into `android/` and `ios/`.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public"
OUTPUT = ROOT / "build" / "native"
CONFIG = ROOT / "capacitor.config.json"
SHELL = SOURCE / "dashboard" / "index.html"

EXCLUDED_FILES = {"_headers", "_redirects", "sw.js", "robots.txt", "sitemap.xml", ".DS_Store"}
EXCLUDED_DIRS = {"strength/admin"}
TEXT_SUFFIXES = {".html", ".js", ".webmanifest", ".json"}
NATIVE_MARKER = '<script>window.__MW_NATIVE=true</script>'


def excluded(rel: Path) -> bool:
    posix = rel.as_posix()
    if rel.name in EXCLUDED_FILES:
        return True
    return any(posix == d or posix.startswith(d + "/") for d in EXCLUDED_DIRS)


def copy_tree() -> list[Path]:
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    copied: list[Path] = []
    for src in sorted(SOURCE.rglob("*")):
        if not src.is_file():
            continue
        rel = src.relative_to(SOURCE)
        if excluded(rel):
            continue
        dest = OUTPUT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        copied.append(rel)
    return copied


def page_dirs(files: list[Path]) -> list[str]:
    dirs = sorted({f.parent.as_posix() for f in files if f.name == "index.html" and f.parent != Path(".")})
    return dirs


def rewrite_links(files: list[Path], dirs: list[str]) -> int:
    """Rewrite `/dir/` style links to `/dir/index.html` for known page directories only.

    API routes (`/api/...`), assets and external URLs are never touched because only
    directories that actually contain an `index.html` in the bundle are rewritten.
    """
    alternation = "|".join(re.escape(d) for d in sorted(dirs, key=len, reverse=True))
    # Attribute form in HTML: ="/dir/" ="/dir/#frag" ="/dir/?query" and the root ="/".
    html_dir = re.compile(r'="/(' + alternation + r')/(["#?])')
    html_root = re.compile(r'(href|content)="/(["#?])')
    # Quoted string form in JS: '/dir/' '/dir/#frag' (the site uses single quotes).
    js_dir = re.compile(r"(['\"])/(" + alternation + r")/(['\"#?])")
    total = 0
    for rel in files:
        if rel.suffix not in {".html", ".js"}:
            continue
        path = OUTPUT / rel
        text = path.read_text(encoding="utf-8")
        original = text
        if rel.suffix == ".html":
            text, n1 = html_dir.subn(r'="/\1/index.html\2', text)
            text, n2 = html_root.subn(r'\1="/index.html\2', text)
            total += n1 + n2
            # Native marker, evaluated before any other script: web code uses it to skip
            # web-only behaviour (service-worker registration) inside the packaged app.
            text = text.replace("<head>", "<head>" + NATIVE_MARKER, 1)
        else:
            text, n = js_dir.subn(r"\1/\2/index.html\3", text)
            total += n
        if text != original:
            path.write_text(text, encoding="utf-8")
    return total


def main() -> int:
    if not SOURCE.is_dir() or not SHELL.is_file():
        print("public/ or public/dashboard/index.html missing: run `npm run build` first", file=sys.stderr)
        return 1
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    files = copy_tree()
    dirs = page_dirs(files)
    # App shell as the root document of the packaged app (web homepage stays untouched in public/).
    shutil.copyfile(SHELL, OUTPUT / "index.html")
    rewritten = rewrite_links(files, dirs)
    # Links that still point at pages deliberately left out of the bundle (e.g. the reviewer
    # console). Capacitor serves the app root for them; they are listed here so the omission is
    # visible instead of silent.
    excluded_pattern = re.compile(r'href="/(' + "|".join(re.escape(d) for d in sorted(EXCLUDED_DIRS)) + r')/')
    links_to_excluded = sorted(
        {rel.as_posix() for rel in files if rel.suffix == ".html" and excluded_pattern.search((OUTPUT / rel).read_text(encoding="utf-8"))}
    )
    manifest = {
        "appId": config["appId"],
        "appName": config["appName"],
        "webDir": config["webDir"],
        "root": "dashboard (MONTE WO app shell)",
        "pages": len(dirs) + 1,
        "files": len(files),
        "rewrittenLinks": rewritten,
        "excluded": sorted(EXCLUDED_FILES - {".DS_Store"}) + sorted(d + "/" for d in EXCLUDED_DIRS),
        "pagesLinkingToExcludedContent": links_to_excluded,
        "note": "Derived from public/ by scripts/build_native.py. Do not edit; rebuild instead.",
    }
    (OUTPUT / "native-build.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"native bundle: {len(files)} files, {len(dirs) + 1} pages, {rewritten} links rewritten -> {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
